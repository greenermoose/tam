#!/usr/bin/env python3
"""Emit the C lookup table from a local WHATWG entities.json snapshot."""

import argparse
import hashlib
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("snapshot", type=Path, help="https://html.spec.whatwg.org/entities.json")
    args = parser.parse_args()
    source = args.snapshot.read_bytes()
    entities = sorted((name[1:-1], item["codepoints"])
                      for name, item in json.loads(source).items() if name.endswith(";"))
    print("/* Generated by tools/generate-html-entities.py.")
    print(" * Source: https://html.spec.whatwg.org/entities.json")
    print(f" * SHA-256: {hashlib.sha256(source).hexdigest()}")
    print(" * Copyright WHATWG (Apple, Google, Mozilla, Microsoft).")
    print(" * SPDX-License-Identifier: BSD-3-Clause (see COPYRIGHT).")
    print(" */\n")
    print(f"#define HTML_ENTITY_MAX_NAME {max(len(name) for name, _ in entities)}\n")
    print("typedef struct {")
    print("    const char *name;")
    print("    uint32_t first, second;")
    print("} html_entity_t;\n")
    print("static const html_entity_t html_entities[] = {")
    for name, codepoints in entities:
        first, second = codepoints if len(codepoints) == 2 else (*codepoints, 0)
        print(f'    {{"{name}", 0x{first:x}, 0x{second:x}}},')
    print("};")


if __name__ == "__main__":
    main()
